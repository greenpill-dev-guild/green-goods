#!/usr/bin/env node
/* Builds the self-contained prototype and the generated markdown from src/, after checking that
   every screen renders every state in every language, every link resolves, and no copy carries an
   em dash or a dollar figure. Plain Node, no dependencies:

     node build.mjs                      writes prototype.html, matrices.md, copy-sheet.md
     node build.mjs --publish <file>     also writes the artifact-ready page (no document skeleton)
*/
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const here = dirname(fileURLToPath(import.meta.url));
const src = (f) => readFileSync(join(here, "src", f), "utf8");
const ORDER = ["kit.js", "member-g.js", "member-v.js", "member-h.js", "steward-g.js", "steward-v.js", "data.js", "diagrams.js"];
const scripts = ORDER.map((f) => `/* ${f} */\n${src(f)}`).join("\n");
const app = `/* app.js */\n${src("app.js")}`;

/* ---------- Checks ---------- */
const ctx = vm.createContext({ console });
vm.runInContext(scripts, ctx, { filename: "prototype-src.js" });
const GG = ctx.GG;
const problems = [];
const screens = GG.screens;
const targetOk = (target, fromId) => {
  const [id, st] = target.split("@");
  const sid = id || fromId;
  const d = screens[sid];
  if (!d) return false;
  return !st || d.states.some((x) => x[0] === st);
};
for (const [key, row] of Object.entries(GG.strings)) {
  if (row.length !== 3 || row.some((x) => !x)) problems.push(`String ${key} needs en, es and pt`);
  if (row.some((x) => x.includes("\u2014"))) problems.push(`String ${key} has an em dash`);
}
for (const id of Object.keys(screens)) {
  const d = screens[id];
  for (const k of ["who", "pre", "auth", "out", "rec", "facts"]) if (!d.notes || !d.notes[k]) problems.push(`${id} notes.${k} missing`);
  for (const [st] of d.states) {
    if (!d.stateNotes || !d.stateNotes[st]) problems.push(`${id}@${st} has no state note`);
    for (const lang of GG.LANGS) {
      GG.lang = lang;
      let html = "";
      for (const variant of [{}, { phone: true }, { wide: true }]) {
        try { html = d.render(st, variant); } catch (e) { problems.push(`${id}@${st} [${lang}] throws: ${e.message}`); continue; }
        if (html.includes("⟦")) problems.push(`${id}@${st} [${lang}] missing string ${html.match(/⟦([^⟧]+)⟧/)[1]}`);
        if (/(^|[^G])\$\s?\d/.test(html.replace(/<[^>]+>/g, " "))) problems.push(`${id}@${st} [${lang}] shows a dollar figure`);
        for (const m of html.matchAll(/data-go="([^"]*)"/g)) if (m[1] && !targetOk(m[1], id)) problems.push(`${id}@${st} links to missing ${m[1]}`);
      }
    }
  }
}
GG.lang = "en";
for (const w of GG.WALKS) for (const [target] of w.steps) if (!targetOk(target)) problems.push(`Walk ${w.id} step ${target} missing`);
for (const m of GG.MAPS) for (const lane of m.lanes) for (const cell of lane.slice(1)) for (const x of cell) if (/^[MS]\d/.test(x) && !targetOk(x)) problems.push(`Map ${m.title} cell ${x} missing`);
for (const o of GG.OWNERS) for (const x of o[1].split(", ")) if (!screens[x]) problems.push(`Owner ${o[0]} lists missing ${x}`);
const covered = new Set(GG.OWNERS.flatMap((o) => o[1].split(", ")));
for (const id of Object.keys(screens)) if (!covered.has(id)) problems.push(`${id} has no implementation owner`);
const allText = [scripts, app, src("styles.css"), src("shell.html")].join("\n");
if (allText.includes("\u2014")) problems.push("An em dash appears in the source");
if (problems.length) {
  console.error(`Build stopped: ${problems.length} problem(s)\n- ` + problems.slice(0, 80).join("\n- "));
  process.exit(1);
}

/* ---------- Page ---------- */
const version = GG.VERSION.label;
const shell = src("shell.html")
  .replace("/*__STYLES__*/", () => src("styles.css"))
  .replace("/*__VERSION__*/", () => version)
  .replace("/*__SCRIPTS__*/", () => `${scripts}\n${app}`);
const cut = shell.indexOf('<div class="bar">');
const head = shell.slice(0, cut);
const body = shell.slice(cut);
const banner = `<!-- Generated by build.mjs from src/. Edit src/ and rebuild; do not edit this file by hand. ${GG.VERSION.name}. -->\n`;
const full = `<!doctype html>\n${banner}<html lang="en">\n<head>\n<meta charset="utf-8">\n<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">\n${head}</head>\n<body>\n${body}</body>\n</html>\n`;
writeFileSync(join(here, "prototype.html"), full);
const pubIdx = process.argv.indexOf("--publish");
if (pubIdx > 0) writeFileSync(process.argv[pubIdx + 1], `${banner}${shell}`);

/* ---------- Markdown ---------- */
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const tagText = (list) => (list || []).map((k) => (GG.TAGS[k] ? GG.TAGS[k][1] : k)).join("; ");
const KIND = { default: "default", loading: "loading", empty: "empty", unavailable: "unavailable", stale: "stale", paused: "paused", rejected: "rejected", delayed: "delayed", failure: "failure", recovery: "recovery", success: "success", offline: "offline", pending: "pending", blocked: "blocked", permission: "permission" };
let md = `# PRD-1299 matrices (${GG.VERSION.name})\n\nGenerated by \`build.mjs\` from the prototype's data, so these tables match \`prototype.html\`. Do not edit by hand.\n\n`;
md += `## Screen and state inventory\n\n| ID | Surface | Screen | Owner | States | Status |\n|---|---|---|---|---|---|\n`;
for (const [id, d] of Object.entries(screens)) {
  md += `| ${id} | ${d.surface === "member" ? "Member app" : "Cockpit"} | ${cell(d.title)}${d.entry ? " (entry)" : ""} | ${cell(d.prd)} | ${d.states.map((x) => `\`${x[0]}\` ${KIND[x[2]]}`).join("<br>")} | ${cell(tagText(d.notes.tags))} |\n`;
}
md += `\n## Screen notes\n\n`;
for (const [id, d] of Object.entries(screens)) {
  const n = d.notes;
  md += `### ${id} · ${d.title}\n\n- **Actor and account:** ${n.who}\n- **Preconditions and evidence:** ${n.pre}\n- **Reviews and authorizes:** ${n.auth}\n- **Pending, success, failure:** ${n.out}\n- **Recovery and who:** ${n.rec}\n- **Contract and projection facts:** ${n.facts}\n\n| State | Kind | What it shows | Screen reader |\n|---|---|---|---|\n`;
  for (const [st, label, kind] of d.states) { const sn = d.stateNotes[st] || {}; md += `| \`${st}\` | ${KIND[kind]} | ${cell(sn.say || label)} | ${cell(sn.sr)} |\n`; }
  md += `\n`;
}
md += `## Role and action matrix\n\n| Action | Actor | Account | Preconditions | Evidence | Reviews and authorizes | Pending | Success | Failure | Recovery and who | Screens | Status |\n|---|---|---|---|---|---|---|---|---|---|---|---|\n`;
for (const r of GG.ROLES) md += `| ${cell(r.a)} | ${cell(r.who)} | ${cell(r.acct)} | ${cell(r.pre)} | ${cell(r.ev)} | ${cell(r.auth)} | ${cell(r.pend)} | ${cell(r.ok)} | ${cell(r.fail)} | ${cell(r.rec)} | ${cell(r.scr)} | ${cell(tagText(r.tags))} |\n`;
md += `\n## Decisions and dependencies\n\n| ID | For Afo | Question | Recommended | Why | Owner |\n|---|---|---|---|---|---|\n`;
for (const d of GG.DECISIONS) md += `| ${d.id} | ${d.afo ? "Yes" : "No"} | ${cell(d.t)} | ${cell(d.rec)} | ${cell(d.why)} | ${cell(d.owner)} |\n`;
md += `\n## Walks\n\n`;
for (const w of GG.WALKS) md += `- **${w.id} ${w.title}:** ${w.steps.map((s) => `\`${s[0]}\``).join(" → ")}\n`;
writeFileSync(join(here, "matrices.md"), md);

let copy = `# PRD-1299 copy sheet (${GG.VERSION.name})\n\nGenerated by \`build.mjs\` from the prototype's strings. English is the source; Spanish follows the shipped catalogs' terms; **Portuguese is a proposal for Gui's review in PRD-1312.** User-authored content (offer titles, descriptions, garden and people names) stays in its author's language and isn't listed. Do not edit by hand.\n\n## Terminology decisions\n\n| ID | Term | Status | English | Spanish | Portuguese (for Gui) | Note |\n|---|---|---|---|---|---|---|\n`;
for (const x of GG.TERMS) copy += `| ${x.id} | ${cell(x.term)} | ${cell(x.st)} | ${cell(x.en)} | ${cell(x.es)} | ${cell(x.pt)} | ${cell(x.note)} |\n`;
copy += `\n## Product strings (${Object.keys(GG.strings).length})\n\n| Key | English | Spanish | Portuguese (for Gui) |\n|---|---|---|---|\n`;
for (const [k, r] of Object.entries(GG.strings)) copy += `| \`${k}\` | ${cell(r[0])} | ${cell(r[1])} | ${cell(r[2])} |\n`;
writeFileSync(join(here, "copy-sheet.md"), copy);

const states = Object.values(screens).reduce((a, d) => a + d.states.length, 0);
console.log(`Built ${GG.VERSION.name}: ${Object.keys(screens).length} screens, ${states} states, ${Object.keys(GG.strings).length} strings x 3 languages, ${GG.WALKS.length} walks. Checks passed.`);
