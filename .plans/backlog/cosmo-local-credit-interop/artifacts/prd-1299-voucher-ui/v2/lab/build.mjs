// Assembles voucher-lab.html: the lab shell, the screen kit CSS, the Remix Icon sprite, the EN/ES/PT copy,
// the screen/state crosswalk and every screen source. It also writes ../copy-sheet.md and ../crosswalk.md
// from the same copy and crosswalk files, so the handoff tables always match the lab.
// Usage: node build.mjs [output path]; the default writes ../voucher-lab.html next to this folder.
import fs from 'node:fs';
import path from 'node:path';

const dir = path.dirname(new URL(import.meta.url).pathname);
const ids = ['Main', 'Visit', 'Offer', 'Pay', 'Send', 'Status', 'ProviderReview', 'BuyerDeposits', 'Inspector',
  'VOffer', 'VSetup', 'Holder', 'Split', 'IssuerDesk', 'EscrowInspector', 'Wallet', 'Exchange', 'Rewards', 'RewardsDesk', 'IssuersDesk',
  'SOffer', 'SPay', 'SPurchase', 'SRedeem', 'SReward', 'SExchange', 'SWallet', 'SFunds', 'SRequests', 'SIssuer',
  'SServices', 'SOnboard', 'SMyService', 'SBrief', 'SIssuers'];

const sources = {};
for (const id of ids) {
  const s = fs.readFileSync(path.join(dir, 'screens', id + '.dc.html'), 'utf8');
  const title = (s.match(/<title>([^<]*)<\/title>/) || [])[1] || id;
  const tpl = s.split('</helmet>')[1].split('</x-dc>')[0].trim();
  const m = s.match(/<script type="text\/x-dc" data-dc-script data-props='([^']*)'>([\s\S]*?)<\/script>/);
  if (!m) throw new Error('No logic block in ' + id);
  const props = JSON.parse(m[1].replace(/&#39;/g, "'").replace(/&amp;/g, '&'));
  sources[id] = { title, tpl, js: m[2], props };
}

// Copy: every key carries an aligned [EN, ES, PT] triple. Refuse to build on a gap or an em dash.
const copy = JSON.parse(fs.readFileSync(path.join(dir, 'copy.json'), 'utf8'));
const copyProblems = [];
for (const [key, v] of Object.entries(copy)) {
  if (!Array.isArray(v) || v.length !== 3 || v.some((x) => typeof x !== 'string' || !x.trim())) copyProblems.push(key + ': needs three non-empty strings');
  else if (v.some((x) => x.includes('—'))) copyProblems.push(key + ': contains an em dash');
  else {
    const holes = (x) => (x.match(/\{\w+\}/g) || []).sort().join(',');
    if (holes(v[1]) !== holes(v[0]) || holes(v[2]) !== holes(v[0])) copyProblems.push(key + ': placeholders differ between languages');
  }
}
if (copyProblems.length) throw new Error('Copy problems:\n' + copyProblems.join('\n'));

const crosswalk = JSON.parse(fs.readFileSync(path.join(dir, 'crosswalk.json'), 'utf8'));

const safe = (o) => JSON.stringify(o).replace(/<\//g, '<\\/').replace(/<!--/g, '<\\!--');
const css = fs.readFileSync(path.join(dir, 'gg.css'), 'utf8');
const sprite = fs.readFileSync(path.join(dir, 'remix-sprite.svg'), 'utf8').trim();
let page = fs.readFileSync(path.join(dir, 'shell.html'), 'utf8');
for (const hole of ['/*__GG_CSS__*/', '/*__SOURCES__*/', '/*__COPY__*/', '/*__CROSSWALK__*/', '<!--__SPRITE__-->']) if (!page.includes(hole)) throw new Error('Shell placeholder missing: ' + hole);
page = page.replace('/*__GG_CSS__*/', () => css).replace('/*__SOURCES__*/', () => safe(sources)).replace('/*__COPY__*/', () => safe(copy))
  .replace('/*__CROSSWALK__*/', () => safe(crosswalk)).replace('<!--__SPRITE__-->', () => sprite);
const out = path.resolve(process.argv[2] || path.join(dir, '..', 'voucher-lab.html'));
fs.writeFileSync(out, page);
console.log('wrote', out, (page.length / 1024).toFixed(0) + ' KB');

// The copy sheet, grouped by screen prefix.
const groups = { c: 'Shared words', who: 'Names', u: 'Units', of: 'Offer', pay: 'Review sheet', pu: 'G$ purchase', rd: 'Voucher booking',
  rw: 'Request rewards', ex: 'Exchange', wl: 'Wallet', sv: 'Services', ob: 'Your service setup (member issuer)', ms: 'Your service (member issuer)', br: 'Project brief',
  fn: 'Steward: Funds (home garden)', rq: 'Steward: Promises (provider garden)', is: 'Steward: Voucher bookings (issuer)', iss: 'Steward: Voucher issuers (Community)' };
const cell = (s) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');
let sheet = '# PRD-1299 pilot copy sheet: EN, ES, PT\n\nGenerated by `lab/build.mjs` from `lab/copy.json`. Edit the JSON, not this file.\n\n'
  + '- **Status:** draft copy for Afo\'s review, not approved. Every key has all three languages.\n'
  + '- **Portuguese:** awaiting Gui\'s review through PRD-1312. **Spanish:** not yet reviewed by a native speaker.\n'
  + '- **Casing:** English titles and actions use Title Case; Spanish and Portuguese use sentence case (DL-012).\n'
  + '- **Terms:** voucher = vale; promise = promesa / promessa; steward = responsable / responsável; pool = fondo / fundo; '
  + 'Redeem = canjear / resgatar. The Spanish and Portuguese Redeem verbs collide with today\'s vault strings until the vault verb is chosen.\n'
  + '- **Amounts and dates** are fictional and formatted per language in the screens.\n';
const byGroup = {};
for (const [key, v] of Object.entries(copy)) { const g = key.split('.')[0]; (byGroup[g] = byGroup[g] || []).push([key, v]); }
for (const g of Object.keys(byGroup)) {
  sheet += '\n## ' + (groups[g] || g) + '\n\n| Key | EN | ES | PT (awaiting Gui) |\n|---|---|---|---|\n';
  for (const [key, v] of byGroup[g]) sheet += '| `' + key + '` | ' + v.map(cell).join(' | ') + ' |\n';
}
fs.writeFileSync(path.join(dir, '..', 'copy-sheet.md'), sheet);

// The crosswalk, one table per journey.
let cw = '# PRD-1299 pilot screen and state crosswalk\n\nGenerated by `lab/build.mjs` from `lab/crosswalk.json`. Edit the JSON, not this file.\n\n'
  + crosswalk.intro.map((p) => '- ' + p).join('\n') + '\n';
for (const j of crosswalk.journeys) {
  cw += '\n## ' + j.title + '\n\n| Screen and state | Implemented behavior and source | Local proof (evidence class) | Remaining gaps and live blockers | Future ideas outside the pilot |\n|---|---|---|---|---|\n';
  for (const r of j.rows) cw += '| ' + [r.state, r.behavior, r.proof, r.gaps, r.future || ''].map(cell).join(' | ') + ' |\n';
}
fs.writeFileSync(path.join(dir, '..', 'crosswalk.md'), cw);
console.log('wrote copy-sheet.md (' + Object.keys(copy).length + ' keys) and crosswalk.md (' + crosswalk.journeys.reduce((n, j) => n + j.rows.length, 0) + ' rows)');
